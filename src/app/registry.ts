import {
  commandRegistry,
  assemblySchema,
  type CommandDefinition,
  type PayloadSchema,
} from '../core/commands';

const string: PayloadSchema = { type: 'string' };
function entry(
  name: string,
  description: string,
  properties: Record<string, PayloadSchema>,
  required: string[],
  mutates: boolean,
  payload: Record<string, unknown>,
): CommandDefinition {
  return {
    name,
    description,
    schema: {
      type: 'object',
      properties,
      required,
      additionalProperties: false,
    },
    mutates,
    examples: [{ name, payload }],
  };
}
